import { Command } from "https://deno.land/x/cmd@v1.2.0/mod.ts";
import { join, basename } from "jsr:@std/path@^0.225.1";
import * as dotenv from "jsr:@std/dotenv@^0.225.1";
import { UnifiedCrateData, extendedGPRProject, filterCompleteCrates, createBlock, getCogralysEnginePath } from "../utils.ts";
import { PROJECT_ROOT } from "../../config.ts";

const globalLogFilePath = `$PROJECT_ROOT/cogralys-run-all-$xpNum-j$max_procs.log`;
let defaultCogralysEnginePath = "";
try {
    defaultCogralysEnginePath = getCogralysEnginePath()
} catch (_) {
    defaultCogralysEnginePath = "NOT FOUND"
}

export function initializeModule(program: Command): void {
    program
        .command("bench-cogralys")
        .description(
            "Generate a bash script to run cogralys engine and generate all db files (Neo4J queries in a JSON file)."
        )
        .option(
            "-c, --cratesPath <path>",
            "Path to a file that contains a list of known crates.",
            join(PROJECT_ROOT, "cratesPath.json")
        )
        .option("-e, --execPath <path>", "Path to cogralys bin/exec file", defaultCogralysEnginePath)
        .option("-l, --log4jSettingsPath <path>", "Path to log4j settings", "$PROJECT_ROOT/rootfs/home/bin/log4j.properties")
        .action(
            (options: { cratesPath: string, execPath: string, log4jSettingsPath: string }) => {
                const cratesDB: UnifiedCrateData = JSON.parse(Deno.readTextFileSync(join(PROJECT_ROOT, "cratesDB.json")));
                const projects : extendedGPRProject[] = filterCompleteCrates(cratesDB.crates);

                let resultFile = `#!/bin/bash

${createBlock("WARNING: DO NOT EDIT THIS FILE MANUALY\n" +
"This file is generated with: cogralys-bench-util bench-cogralys")}

# Initialize variables
xpNum=0
# Default number of maximum processes
max_procs=0
# Root of the benchmark project
PROJECT_ROOT=$PWD

# Function to display help information
function show_help() {
    echo "Usage: $0 [-xpNum <number>] [-j <max_procs>] [-h|--help]"
    echo "  -xpNum <number>    Set the experience number."
    echo "  -j <max_procs>     Set the maximum number of processes."
    echo "  -h, --help         Show help information."
}

# Loop through arguments and handle options
while [[ "$#" -gt 0 ]]; do
    case $1 in
        -xpNum)
            xpNum="$2"
            shift 2
            ;;
        -j)
            max_procs="$2"
            shift 2
            ;;
        -h|--help)
            show_help
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            show_help
            exit 1
            ;;
    esac
done

echo "" > ${globalLogFilePath}

`;

                let i = 1;
                const maxProject = projects.length;
                for (const project of projects) {
                    resultFile += generateCommandBlock(i, maxProject, project, options);
                    i++;
                }

                Deno.writeTextFileSync(join(PROJECT_ROOT, "cogralys_benchmark.sh"), resultFile);
            }
        );
}

function generateCommandBlock(i: number, maxProject: number, project: extendedGPRProject, options: any): string {
    return `echo [${i}/${maxProject}] START
cd "$PROJECT_ROOT/${project.alireTomlPath}"
echo "[START] process ${project.alireTomlPath}: ${project.gprPath}" >> ${globalLogFilePath}
echo "" > cogralys-run-$xpNum-j$max_procs.log
{ time deno run --config $PROJECT_ROOT/deno.jsonc --allow-read --allow-write --allow-env --allow-run $PROJECT_ROOT/utils/executeCogralysWithWatchdog.ts '${JSON.stringify({
    path: project.alireTomlPath,
    command: [
        options.execPath,
        [
            "-dvx",
            "-p",
            project.gprPath.trim(),
            `@${project.gprPath.replace(".gpr", ".units").trim()}`
        ],
        {
            env: {
                ...dotenv.loadSync({
                    envPath: join(project.alireTomlPath, ".env"),
                }),
                DRY_RUN: "True",
                LOGGER_CONFIG: options.log4jSettingsPath,
                NEO4J_RESULT_DIR: join("." + basename(project.gprPath).replace(".gpr", "").trim(), ".atdgb")
            }
        },
    ]
})}'; } &> >(tee -a cogralys-run-${basename(project.gprPath).replace(".gpr", "")}-$xpNum-j$max_procs.log ${globalLogFilePath} > /dev/null)
echo "[END] process ${project.alireTomlPath}: ${project.gprPath}" >> ${globalLogFilePath}
echo [${i}/${maxProject}] END
`;
}
