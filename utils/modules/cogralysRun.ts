import { UnifiedCrateData, extendedGPRProject, filterCompleteCrates, getAllIgnoredCrates, createBlock } from "../utils.ts";

export function initializeModule(program: Command): void {
    program
        .command("bench-cogralys")
        .description(
            "Generate a bash script to run cogralys engine and generate all db files (Neo4J queries in a JSON file)."
        )
        .option(
            "-c, --cratesPath <path>",
            "Path to a file that contains a list of known crates.",
            "/workspaces/bench-source/cratesPath.json"
        )
        .option("-i, --ignoredUnknownCrates <path>", "Name of the output file", "/workspaces/bench-source/unknownCrates.ignore")
        .option("-e, --execPath <path>", "Path to cogralys bin/exec file", "/home/devy/bin/atgdb")
        .option("-l, --log4jSettingsPath <path>", "Path to log4j settings", "/home/devy/bin/log4j.properties")
        .action(
            (options: { cratesPath: string, ignoredUnknownCrates: string, execPath: string, log4jSettingsPath: string }) => {
                const cratesDB: UnifiedCrateData = JSON.parse(Deno.readTextFileSync("/workspaces/bench-source/cratesDB.json"));
                const ignoredUnknownCrates : string[] = getAllIgnoredCrates(cratesDB);
                const projects : extendedGPRProject[] = filterCompleteCrates(cratesDB.crates);
                const knowCrates = projects.map(elt => elt.crateName);
                const paths = projects.map(elt => elt.alireTomlPath);

                let resultFile = `#!/bin/bash

${createBlock("WARNING: DO NOT EDIT THIS FILE MANUALY\n" +
"This file is generated with cogralys-bench-util bench-cogralys")}

# Initialize variables
xpNum=0
max_procs=8

# Function to display help information
function show_help() {
    echo "Usage: $0 [-xpNum <number>] [-j <max_procs>] [-h|--help]"
    echo "  -xpNum <number>    Set the experience number."
    echo "  -j <max_procs>     Set the maximum number of processes."
    echo "  -h, --help         Show help information."
}

# Loop through arguments and handle options
while [[ "$#" -gt 0 ]]; do
    case $1 in
        -xpNum)
            xpNum="$2"
            shift 2
            ;;
        -j)
            max_procs="$2"
            shift 2
            ;;
        -h|--help)
            show_help
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            show_help
            exit 1
            ;;
    esac
done

echo "" > /workspaces/bench-source/cogralys-run-all-$xpNum-j$max_procs.log

`;

                let i = 1;
                const maxProject = paths.length;
                for (const project of projects) {
                    resultFile += generateCommandBlock(i, maxProject, project, options);
                    i++;
                }

                // for (const path of paths) {
                //     const alireFilePath = `${path}${path.endsWith("/") ? "alire.toml" : path.endsWith("alire.toml") ? "" : "/alire.toml"}`;
                //     const alireToml = parseToml(Deno.readTextFileSync(alireFilePath));
                //     const projectFilesPath = alireToml["project-files"] as string[];

                //     if (projectFilesPath) {
                //         for (const filePath of projectFilesPath) {
                //             const currentPath = join(dirname(alireFilePath), filePath);

                //             if (currentPath.match(new RegExp(`src/(${ignoredUnknownCrates.join("|")})/`))) {
                //                 continue;
                //             }

                //             resultFile += generateCommandBlock(i, maxProject, alireFilePath, currentPath, options);
                //             i++;
                //         }
                //     } else {
                //         const filePath = (alireToml["name"] as string) + ".gpr";
                //         const currentPath = join(dirname(alireFilePath), filePath);

                //         if (!currentPath.match(new RegExp(`src/(${ignoredUnknownCrates.join("|")})/`))) {
                //             resultFile += generateCommandBlock(i, maxProject, alireFilePath, currentPath, options);
                //             i++;
                //         }
                //     }
                // }

                Deno.writeTextFileSync("/workspaces/bench-source/cogralys_benchmark.sh", resultFile);
            }
        );
}

function generateCommandBlock(i: number, maxProject: number, project: extendedGPRProject, options: any): string {
    return `echo [${i}/${maxProject}] START
cd "${project.alireTomlPath}"
echo "[START] process ${project.alireTomlPath}: ${project.gprPath}" >> /workspaces/bench-source/cogralys-run-all-$xpNum-j$max_procs.log
echo "" > cogralys-run-$xpNum-j$max_procs.log
{ time deno run --config /workspaces/bench-source/deno.jsonc --allow-read --allow-write --allow-env --allow-run /workspaces/bench-source/utils/executeCogralysWithWatchdog.ts '${JSON.stringify({
    path: project.alireTomlPath,
    command: [
        options.execPath,
        [
            "-dvx",
            "-p",
            project.gprPath.trim(),
            `@${project.gprPath.replace(".gpr", ".units").trim()}`
        ],
        {
            env: {
                ...dotenv.loadSync({
                    envPath: join(project.alireTomlPath, ".env"),
                }),
                DRY_RUN: "True",
                LOGGER_CONFIG: options.log4jSettingsPath,
                NEO4J_RESULT_DIR: join("." + basename(project.gprPath).replace(".gpr", "").trim(), ".atdgb")
            }
        },
    ]
})}'; } &> >(tee -a cogralys-run-${basename(project.gprPath).replace(".gpr", "")}-$xpNum-j$max_procs.log /workspaces/bench-source/cogralys-run-all-$xpNum-j$max_procs.log > /dev/null)
echo "[END] process ${project.alireTomlPath}: ${project.gprPath}" >> /workspaces/bench-source/cogralys-run-all-$xpNum-j$max_procs.log
echo [${i}/${maxProject}] END
`;
}
