import { Command } from "https://deno.land/x/cmd@v1.2.0/mod.ts";
import { join, basename } from "jsr:@std/path@^0.225.1";
import * as dotenv from "jsr:@std/dotenv@^0.225.1";
import { filterCompleteCrates, createBlock, getCogralysEnginePath } from "../utils.ts";
import { UnifiedCrateData, extendedGPRProject } from "../types.ts";
import { PROJECT_ROOT, COGRALYS_DIR_NAME } from "../../config.ts";

let defaultCogralysEnginePath = "";
try {
    defaultCogralysEnginePath = getCogralysEnginePath()
} catch (_) {
    defaultCogralysEnginePath = "NOT FOUND"
}

type optionsType = { cratesPath: string, execPath: string, log4jSettingsPath: string };

export function initializeModule(program: Command): void {
    program
        .command("bench-cogralys")
        .description(
            "Generate a bash script to run cogralys engine and generate all db files (Neo4J queries in a JSON file)."
        )
        .option(
            "-c, --cratesPath <path>",
            "Path to a file that contains a list of known crates.",
            join(PROJECT_ROOT, "cratesPath.json")
        )
        .option("-e, --execPath <path>", "Path to cogralys bin/exec file", defaultCogralysEnginePath)
        .option("-l, --log4jSettingsPath <path>", "Path to log4j settings", "$PROJECT_ROOT/rootfs/home/bin/log4j.properties")
        .action(
            (options: optionsType) => {
                options.execPath = getCogralysEnginePath(options.execPath);
                const cratesDB: UnifiedCrateData = JSON.parse(Deno.readTextFileSync(join(PROJECT_ROOT, "cratesDB.json")));
                const projects : extendedGPRProject[] = filterCompleteCrates(cratesDB.crates);

                let resultFile = generateScriptHeader();
                resultFile += generateHelperFunctions();
                resultFile += generateMainLogic(generateProjectsArray(projects, options));

                Deno.writeTextFileSync(join(PROJECT_ROOT, "cogralys_benchmark.sh"), resultFile);
            }
        );
}

function generateScriptHeader(): string {
    return `#!/bin/bash

${createBlock("WARNING: DO NOT EDIT THIS FILE MANUALLY\n" +
"This file is generated with: cogralys-bench-util bench-cogralys")}

# Initialize variables
xpNum=0
PROJECT_ROOT=$PWD
# If the benchmark is inside a docker container and the Neo4j DB on the host, use: bolt://host.docker.internal:7687
# If directly running from the host computer, use: bolt://localhost:7687
NEO4J_HOST="bolt://localhost:7687"
NEO4J_USER="neo4j"
NEO4J_PASS="auieauie"
DENO_RUN_ARGS="--config "$PROJECT_ROOT/deno.jsonc" --allow-all --unsafely-ignore-certificate-errors --unstable-ffi"

`;
}

function generateHelperFunctions(): string {
    return `
# Function to handle signal (CTRL+C, CTRL+\\)
function signalHandler()
{
  echo "Signal recieved, safely end the script"
  exit 1
}

# Function to get current date and time
get_datetime() {
    date "+%Y-%m-%d %H:%M:%S"
}

# Function to display help information
show_help() {
    echo "Usage: $0 [-xpNum <number>] [-h|--help]"
    echo "  -xpNum <number>                    Set the experience number."
    echo "  -n, --neo4jHost <URI>              Bolt URI of Neo4j database, with port (e.g.: bolt://domain.com:7687)."
    echo "  --username <userName>              Username used to login to Neo4j database."
    echo "  --password <password>              Password used to login to Neo4j database."
    echo "  -r, --resume <step:projectStep>    Resume from a specific step and project step (e.g., 3:2)."
    echo "  -h, --help                         Show help information."
}

# Save the current state of the script. Useful to resume the script later.
save_checkpoint() {
  echo "$current_step:$current_project_step" > "$checkpoint_file"
}

# Load the script to the latest state (if exists)
load_checkpoint() {
  if [ -f "$checkpoint_file" ]; then
      IFS=':' read -r current_step current_project_step < "$checkpoint_file"
  else
      current_step=1
      current_project_step=1
  fi
}

# Function to process a single project
process_project() {
    local project_info=$1
    local project_number=$2
    local total_projects=$3
    IFS='|' read -r crateName alireTomlPath gprPath cogralys_init_args <<< "$project_info"

    local base_name=$(basename "$gprPath" .gpr)
    local log_prefix="cogralys-$base_name-$xpNum"

    echo "[$(get_datetime)] [$project_number/$total_projects] START processing $crateName" | tee -a "$globalLogFilePath"

    cd "$PROJECT_ROOT/$alireTomlPath"
    echo "[$(get_datetime)] [START] processing $crateName > $alireTomlPath: $gprPath" | tee -a "$globalLogFilePath"

    # Clear the log file only if not resuming
    if [ "$resume_requested" = false ]; then
        echo "" > "$log_prefix.log"
    else
        echo -e "\\n## RESUME ##\\n" >> "$log_prefix.log"
    fi

    # Set current_project_step to 1 if it's empty or not a number
    if ! [[ "$current_project_step" =~ ^[0-9]+$ ]] ; then
        current_project_step=1
        save_checkpoint
    fi

    if [ $current_project_step -eq 1 ]; then
        run_cogralys_init "$gprPath" "$log_prefix" "$cogralys_init_args"
        current_project_step=2
        save_checkpoint
    fi

    # Clean ADT files in order to quickly free space
    if [ $current_project_step -eq 2 ]; then
        clean "$alireTomlPath"
        current_project_step=3
        save_checkpoint
    fi

    if [ $current_project_step -eq 3 ]; then
        update_cratesDB "$crateName" "$alireTomlPath" "$gprPath" "$log_prefix"
        current_project_step=4
        save_checkpoint
    fi

    if [ $current_project_step -eq 4 ]; then
        convert_json_to_cypher "$alireTomlPath" "$gprPath"
        current_project_step=5
        save_checkpoint
    fi

    if [ $current_project_step -eq 5 ]; then
        populate_neo4j "$alireTomlPath" "$gprPath" "$log_prefix"
        current_project_step=6
        save_checkpoint
    fi

    if [ $current_project_step -eq 6 ]; then
        run_cogralys_cli "$log_prefix"
        current_project_step=7
        save_checkpoint
    fi

    if [ $current_project_step -eq 7 ]; then
        computeSize "$gprPath" "$log_prefix" "$alireTomlPath" "$cogralys_init_args"
        current_project_step=8
        save_checkpoint
    fi

    if [ $current_project_step -eq 8 ]; then
        clean_db "$log_prefix"
        current_project_step=1
        save_checkpoint
    fi

    echo "[$(get_datetime)] [END] processing $crateName > $alireTomlPath: $gprPath" | tee -a "$globalLogFilePath"
    echo "[$(get_datetime)] [$project_number/$total_projects] END processing $crateName" | tee -a "$globalLogFilePath"
}

run_cogralys_init() {
    local gprPath=$1
    local log_prefix=$2
    local init_args=$3
    echo "[$(get_datetime)] [$gprPath] Start init" | tee -a "$globalLogFilePath"
    /usr/bin/time -v -o "$log_prefix-init.time" deno run $DENO_RUN_ARGS "$PROJECT_ROOT/utils/executeCogralysWithWatchdog.ts" "$init_args" 2>&1 | tee -a "$log_prefix-init.log" "$globalLogFilePath" > /dev/null
    jc --time -p -r < "$log_prefix-init.time" > "$log_prefix-init.time.json"
    echo "[$(get_datetime)] [$gprPath] End init" | tee -a "$globalLogFilePath"
}

update_cratesDB() {
    local crateName=$1
    local alireTomlPath=$2
    local gprPath=$3
    local log_prefix=$4
    echo "[$(get_datetime)] [$gprPath] Start updating cratesDB for this project" | tee -a "$globalLogFilePath"
    deno run $DENO_RUN_ARGS "$PROJECT_ROOT/utils/cogralys-bench-util.ts" update-cratesDB-neo4j-dir -c "$crateName" -w "$alireTomlPath" -g "$gprPath" 2>&1 | tee -a "$globalLogFilePath" > /dev/null
    echo "[$(get_datetime)] [$gprPath] End updating cratesDB for this project" | tee -a "$globalLogFilePath"
}

convert_json_to_cypher() {
    local alireTomlPath=$1
    local gprPath=$2
    echo "[$(get_datetime)] [$gprPath] Start converting Cypher commands from JSON files to a single .cypher file" | tee -a "$globalLogFilePath"
    deno run $DENO_RUN_ARGS "$PROJECT_ROOT/utils/cogralys-bench-util.ts" convert-neo4j-json-to-cypher-file -w "$alireTomlPath" -g "$gprPath"
    echo "[$(get_datetime)] [$gprPath] End converting Cypher commands from JSON files to a single .cypher file" | tee -a "$globalLogFilePath"
}

populate_neo4j() {
    local alireTomlPath=$1
    local gprPath=$2
    local log_prefix=$3
    echo "[$(get_datetime)] [$gprPath] Start populate" | tee -a "$globalLogFilePath"
    /usr/bin/time -v -o "$log_prefix-populate.time" deno run $DENO_RUN_ARGS "$PROJECT_ROOT/utils/cogralys-bench-util.ts" populate-neo4j-single -h "$NEO4J_HOST" --username "$NEO4J_USER" --password "$NEO4J_PASS" -m "cypher" -w "$alireTomlPath" -g "$gprPath" 2>&1 | tee -a "$globalLogFilePath" > /dev/null
    jc --time -p -r < "$log_prefix-populate.time" > "$log_prefix-populate.time.json"
    echo "[$(get_datetime)] [$gprPath] End populate" | tee -a "$globalLogFilePath"
}

run_cogralys_cli() {
    local log_prefix=$1
    echo "[$(get_datetime)] [$gprPath] Start run" | tee -a "$globalLogFilePath"
    /usr/bin/time -v -o "$log_prefix-run.time" deno run $DENO_RUN_ARGS "$PROJECT_ROOT/utils/cogralys-cli/cogralys-cli.ts" -t -h "$NEO4J_HOST" --username "$NEO4J_USER" --password "$NEO4J_PASS" -o "$log_prefix-run.report" 2>&1 | tee -a "$globalLogFilePath" > /dev/null
    jc --time -p -r < "$log_prefix-run.time" > "$log_prefix-run.time.json"
    echo "[$(get_datetime)] [$gprPath] End run" | tee -a "$globalLogFilePath"
}

computeSize() {
    local gprPath=$1
    local log_prefix=$2
    local alireTomlPath=$3
    local cogralys_init_args=$4
    echo "[$(get_datetime)] [$gprPath] Start computing size metrics" | tee -a "$globalLogFilePath"

    total_size_adt=$(du -ch *.adt 2>/dev/null | tail -n 1 | cut -f 1)
    echo "{ \\"size\\": \\"$total_size_adt\\" }" > "$log_prefix.size-adt.json"

    neo4jPath=$PROJECT_ROOT/$alireTomlPath/$(echo "$cogralys_init_args" | jq -r '.command[2].env.NEO4J_RESULT_DIR')
    total_size_cogralys=$(du -ch "$neo4jPath" 2>/dev/null | tail -n 1 | cut -f 1)
    echo "{ \\"size\\": \\"$total_size_cogralys\\" }" > "$log_prefix.size-cogralys.json"

    echo "[$(get_datetime)] [$gprPath] End computing size metrics" | tee -a "$globalLogFilePath"
}

clean_db() {
    local log_prefix=$1
    echo "[$(get_datetime)] [$gprPath] Start cleaning DB" | tee -a "$globalLogFilePath"
    deno run $DENO_RUN_ARGS "$PROJECT_ROOT/utils/cogralys-bench-util.ts" clean-neo4j -h "$NEO4J_HOST" --username "$NEO4J_USER" --password "$NEO4J_PASS"
    echo "[$(get_datetime)] [$gprPath] End cleaning DB" | tee -a "$globalLogFilePath"
}

clean() {
    local alireTomlPath=$1
    echo "[$(get_datetime)] [$alireTomlPath] Start cleaning" | tee -a "$globalLogFilePath"
    # Remove ASIS AST
    rm -f *.ali *.adt
    echo "[$(get_datetime)] [$alireTomlPath] End cleaning" | tee -a "$globalLogFilePath"
}

`;
}

function generateProjectsArray(projects: extendedGPRProject[], options: optionsType): string {
    let projectsArray = "projects=(\n";
    for (const project of projects) {
        const cogralysInitArgs = JSON.stringify({
            path: `$PROJECT_ROOT/${project.alireTomlPath}`,
            command: [
                `${options.execPath}`,
                [
                    "-dvx",
                    "-p",
                    `$PROJECT_ROOT/${project.gprPath}`,
                    `@$PROJECT_ROOT/${project.gprPath.replace(".gpr", ".units")}`
                ],
                {
                    env: {
                        ...dotenv.loadSync({
                            envPath: `$PROJECT_ROOT/${project.alireTomlPath}/.env`,
                        }),
                        DRY_RUN: "True",
                        LOGGER_CONFIG: `${options.log4jSettingsPath}`,
                        NEO4J_RESULT_DIR: `.${basename(project.gprPath, ".gpr")}/${COGRALYS_DIR_NAME}`,
                        NEO4J_HOST: "$NEO4J_HOST"
                    }
                },
            ]
        }).replace(/"/g, '\\"');
        projectsArray += `    "${project.crateName}|${project.alireTomlPath}|${project.gprPath}|${cogralysInitArgs}"\n`;
    }
    projectsArray += ")\n";
    return projectsArray;
}

function generateMainLogic(projects: string): string {
    return `# Initialize resume variables
resume_requested=false
# Parse command line arguments
while [[ "$#" -gt 0 ]]; do
    case $1 in
        -xpNum) xpNum="$2"; shift 2 ;;
        -h|--help) show_help; exit 0 ;;
        -n|--neo4jHost) NEO4J_HOST="$2"; shift 2 ;;
        --username) NEO4J_USER="$2"; shift 2 ;;
        --password) NEO4J_PASS="$2"; shift 2 ;;
        -r|--resume)
          IFS=':' read -r resume_step resume_iteration <<< "$2"
          current_step=$resume_step
          current_project_step=$resume_iteration
          resume_requested=true
          shift 2 ;;
        *) echo "Unknown option: $1"; show_help; exit 1 ;;
    esac
done

${projects}
# Prepare global variables
globalLogFilePath="$PROJECT_ROOT/cogralys-run-all-$xpNum.log"

# Get total number of projects
total_projects=\${#projects[@]}

checkpoint_file="$PROJECT_ROOT/benchmark-cogralys-$xpNum.checkpoint"

# Load the current state if not set by resume option
if [ "$resume_requested" = false ] && [ -f "$checkpoint_file" ]; then
    load_checkpoint
    resume_requested=true
fi

# Clear the global log file only if not resuming
if [ "$resume_requested" = false ]; then
    echo "" > "$globalLogFilePath"
else
    echo -e "\\n## RESUME ##\\n" | tee -a "$globalLogFilePath"
fi

current_step=$((current_step-1))

trap 'signalHandler' SIGINT
trap 'signalHandler' SIGQUIT

# Process projects sequentially
for i in "\${!projects[@]}"; do
    if [ $i -lt $current_step ]; then
        continue
    fi
    project_number=$((i+1))
    current_step=$project_number
    save_checkpoint
    process_project "\${projects[$i]}" "$project_number" "$total_projects"
done

echo "All projects ($total_projects) processed."
rm "$checkpoint_file"
`;
}
