import { join } from "jsr:@std/path@^0.225.1";
import { Command } from "https://deno.land/x/cmd@v1.2.0/mod.ts";
import { capitalCase } from "jsr:@mesqueeb/case-anything";
import { formatNumber } from "../utils.ts";
import { ResultData, ToolKeyType, toolKey } from "../types.ts";
import { PROJECT_ROOT as defaultProjectRoot } from "../../config.ts";
import { OutputFormat, OutputFormatType, TableAlignType, TableCell } from "../formatters/formatters-interface.ts";
import { DocumentExporter } from "../formatters/exporter.ts";

function toTitleCase(value: string) {
    return capitalCase(value.replaceAll("_", " "));
}

type RuleToolCounts = {
    ruleKey: string;
    displayName: string;
    values: Record<ToolKeyType, number>;
};

function collectRuleToolCountsForGpr(resultData: ResultData, gprPath: string): RuleToolCounts[] {
    const rows: RuleToolCounts[] = [];

    for (const [ruleKey, ruleAggregation] of Object.entries(resultData.rules)) {
        const projects = ruleAggregation.all.projects;
        const project = projects.find(p => p.gprPath === gprPath);
        if (!project) continue;

        const values = {} as Record<ToolKeyType, number>;
        for (const tool of toolKey) {
            const issued = project.results[tool]?.issuedMessages?.maxCount ?? 0;
            values[tool] = issued;
        }

        rows.push({
            ruleKey,
            displayName: toTitleCase(ruleKey),
            values
        });
    }

    rows.sort((a, b) => a.displayName.localeCompare(b.displayName));
    return rows;
}

function formatGprRuleMessagesTable(rows: RuleToolCounts[], gprPath: string, outputFormat: OutputFormatType): string {
    if (rows.length === 0) {
        return `No results found for project '${gprPath}'.`;
    }

    const exporter = new DocumentExporter(outputFormat);

    const columns: TableCell[] = [
        { name: "Rule", key: "rule", align: "left" },
        ...toolKey.map(tool => ({
            name: toTitleCase(tool),
            key: tool,
            align: "right" as TableAlignType,
            format: (value: number) => formatNumber(value)
        }))
    ];

    const tableData = rows.map(row => {
        const result: Record<string, string | number> = {
            rule: row.displayName
        };
        for (const tool of toolKey) {
            result[tool] = row.values[tool];
        }
        return result;
    });

    const caption = `Issued message maxCount per rule for project: ${gprPath}`;
    return exporter.formatTable(columns, tableData, caption);
}

export function initializeModule(program: Command): void {
    program
        .command("gpr-issued-messages")
        .description(
            "List issued message maxCount per rule and tool for a given GPR using results/result.json generated by generate-report."
        )
        .option(
            "-g, --gpr-path <string>",
            "GPR project path to inspect"
        )
        .option(
            "-r, --root-dir <string>",
            "Root directory where results/result.json is located",
            defaultProjectRoot
        )
        .option(
            "-o, --output <string>",
            `Output format (Possible values: ${OutputFormat.join("|")})`,
            "cli"
        )
        .action(handler);
}

async function handler(options: { gprPath: string; rootDir: string; output: OutputFormatType }) {
    try {
        if (!options.gprPath) {
            console.error("Missing required option: --gpr-path");
            Deno.exit(1);
        }

        const resultJsonPath = join(options.rootDir, "results", "result.json");
        const content = await Deno.readTextFile(resultJsonPath);
        const resultData = JSON.parse(content) as ResultData;

        const rows = collectRuleToolCountsForGpr(resultData, options.gprPath);
        const table = formatGprRuleMessagesTable(rows, options.gprPath, options.output);
        console.log(table);
    } catch (error) {
        console.error("Error generating GPR issued messages report:", error);
        Deno.exit(1);
    }
}

if (import.meta.main) {
    const program = new Command();
    initializeModule(program);
    program.parse(Deno.args);
}
