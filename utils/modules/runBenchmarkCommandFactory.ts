import { basename, join } from "jsr:@std/path@^0.225.1";
import { Command } from "https://deno.land/x/cmd@v1.2.0/mod.ts";
import { extendedGPRProject, UnifiedCrateData, filterCompleteCrates, createBlock } from "../utils.ts";
import { PROJECT_ROOT } from "../../config.ts";

export function initializeModule(program: Command, settings: {
    commandName: string,
    description: string,
    command: string[],
    ruleFile: string,
}): void {
    program
        .command(settings.commandName)
        .description(
            settings.description
        )
        .action(() => {
            const crates: UnifiedCrateData = JSON.parse(Deno.readTextFileSync(join(PROJECT_ROOT, "cratesDB.json")));
            const projects : extendedGPRProject[] = filterCompleteCrates(crates.crates);

            const maxProject = projects.length;
            const globalLogFilePath = `$PROJECT_ROOT/${settings.command[0]}-all-$xpNum-j$max_procs.log`;

            let i = 1;
            let resultFile = `#!/bin/bash

${createBlock("WARNING: DO NOT EDIT THIS FILE MANUALY\n" +
"This file is generated with: cogralys-bench-util bench-" + settings.command[0])}

# Initialize variables
xpNum=0
# Default number of maximum processes
max_procs=0
# Root of the benchmark project
PROJECT_ROOT=$PWD
# Path to the rule file
ruleFile="${settings.ruleFile}"

# Function to display help information
function show_help() {
    echo "Usage: $0 [-xpNum <number>] [-j <max_procs>] [-h|--help]"
    echo "  -xpNum <number>    Set the experience number."
    echo "  -j <max_procs>     Set the maximum number of processes."
    echo "  -rule <path>       Set the path to the rule file."
    echo "  -h, --help         Show help information."
}

# Loop through arguments and handle options
while [[ "$#" -gt 0 ]]; do
    case $1 in
        -xpNum)
            xpNum="$2"
            shift 2  # Advance past the argument value
            ;;
        -j)
            max_procs="$2"
            shift 2  # Advance past the argument value
            ;;
        -rule)
            ruleFile="$2"
            shift 2  # Advance past the argument value
            ;;
        -h|--help)
            show_help
            exit 0
            ;;
        *)  # Handle unknown options
            echo "Unknown option: $1"
            show_help
            exit 1
            ;;
    esac
done

echo "" > ${globalLogFilePath}\n
`;

            for (const project of projects) {
                const localFileLogName = `${settings.command[0]}-${basename(project.gprPath).replace(".gpr", "")}-$xpNum-j$max_procs`;
                resultFile += `echo [${i}/${maxProject}] START\n`;
                resultFile += `cd "$PROJECT_ROOT/${project.alireTomlPath}"\n`;

                resultFile += `echo "[START] process ${project.alireTomlPath}: ${project.gprPath}" >> ${globalLogFilePath}\n`;
                resultFile += `echo "" > ${settings.command[0]}-$xpNum-j$max_procs.log\n`;
                resultFile += `{ /usr/bin/time -v -o ${localFileLogName}.time alr exec -- ` +
                settings.command
                    .map(item => item.includes("%PRJ%") ?
                        item.replace("%PRJ%", "$PROJECT_ROOT/" + project.gprPath) : item)
                    .map(item => item.includes("%UNITS%") ?
                        item.replace("%UNITS%", "$PROJECT_ROOT/" + project.gprPath.replace(".gpr", ".units")) : item)
                    .map(item => item.includes("%PRJ_NAME%") ?
                    item.replace("%PRJ_NAME%", basename(project.gprPath).replace(".gpr", "")) : item)
                    .join(" ") +
                    `; } &> >(tee -a ${localFileLogName}.log ${globalLogFilePath} > /dev/null)\n`;
                resultFile += `cat ${localFileLogName}.time | jc --time -p -r > ${localFileLogName}.time.json\n`;
                resultFile += `echo "[END] process ${project.alireTomlPath}: ${project.gprPath}" >> ${globalLogFilePath}\n`;
                resultFile += `echo [${i}/${maxProject}] END\n`;
                i++;
            }

            Deno.writeTextFileSync(join(PROJECT_ROOT, `${settings.command[0]}_benchmark.sh`), resultFile);
        });
}
