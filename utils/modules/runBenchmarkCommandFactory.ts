import { basename, join } from "jsr:@std/path@^0.225.1";
import { Command } from "https://deno.land/x/cmd@v1.2.0/mod.ts";
import { extendedGPRProject, UnifiedCrateData, filterCompleteCrates, createBlock } from "../utils.ts";
import { PROJECT_ROOT } from "../../config.ts";

export function initializeModule(program: Command, settings: {
    commandName: string,
    description: string,
    command: string[],
    ruleFile: string,
}): void {
    program
        .command(settings.commandName)
        .description(
            settings.description
        )
        .action(() => {
            const crates: UnifiedCrateData = JSON.parse(Deno.readTextFileSync(join(PROJECT_ROOT, "cratesDB.json")));
            const projects : extendedGPRProject[] = filterCompleteCrates(crates.crates);

            const commandName = settings.command[0];
            const globalLogFilePath = `$PROJECT_ROOT/${commandName}-all-$xpNum-j$max_procs.log`;

            let resultFile = generateScriptHeader(commandName, settings.ruleFile);
            resultFile += generateHelperFunctions(commandName);
            resultFile += generateMainLogic(globalLogFilePath, generateProjectsArray(projects, settings.command));

            Deno.writeTextFileSync(join(PROJECT_ROOT, `${commandName}_benchmark.sh`), resultFile);
        });
}

function generateScriptHeader(commandName: string, ruleFile: string): string {
    return `#!/bin/bash

${createBlock("WARNING: DO NOT EDIT THIS FILE MANUALY\n" +
"This file is generated with: cogralys-bench-util bench-" + commandName)}

# Initialize variables
xpNum=0
# Default number of maximum processes
max_procs=0
# Root of the benchmark project
PROJECT_ROOT=$PWD
# Path to the rule file
ruleFile="${ruleFile}"
# Suffix of log file
logSuffix=""
`;
}

function generateHelperFunctions(commandName: string): string {
    return `
# Function to get current date and time
get_datetime() {
    date "+%Y-%m-%d %H:%M:%S"
}

# Function to display help information
function show_help() {
    echo "Usage: $0 [--xpNum <number>] [-j <max_procs>] [-h|--help]"
    echo "  --xpNum <number>          Set the experience number."
    echo "  -j <max_procs>            Set the maximum number of processes."
    echo "  --rule <path>             Set the path to the rule file."
    echo "  -s, --suffix <string>     Suffix used on the name of logs files."
    echo "  -h, --help                Show help information."
}

# Function to process a single project
process_project() {
    local project_info=$1
    local project_number=$2
    local total_projects=$3
    IFS='|' read -r crateName alireTomlPath gprPath command <<< "$project_info"

    local base_name=$(basename "$gprPath" .gpr)
    local log_prefix="${commandName}-$base_name-$xpNum-j$max_procs$logSuffix"

    echo "[$(get_datetime)] [$project_number/$total_projects] START" | tee -a "$globalLogFilePath"
    cd "$PROJECT_ROOT/$alireTomlPath"

    echo "[$(get_datetime)] [START] processing $crateName > $alireTomlPath > $gprPath" | tee -a "$globalLogFilePath"
    echo "" > "$log_prefix.log"

    run_command "$gprPath" "$log_prefix" "$command"
    clean "$gprPath"

    echo "[$(get_datetime)] [END] processing $crateName > $alireTomlPath > $gprPath" | tee -a "$globalLogFilePath"
    echo "[$(get_datetime)] [$project_number/$total_projects] END" | tee -a "$globalLogFilePath"
}

run_command() {
    local gprPath=$1
    local log_prefix=$2
    local command="$3"

    echo "[$(get_datetime)] [$gprPath] Start xp" | tee -a "$globalLogFilePath"
    /usr/bin/time -v -o "$log_prefix.time" alr exec -- $command 2>&1 | tee -a "$log_prefix.log" "$globalLogFilePath" > /dev/null
    jc --time -p -r < "$log_prefix.time" > "$log_prefix.time.json"
    echo "[$(get_datetime)] [$gprPath] End xp" | tee -a "$globalLogFilePath"
}

clean() {
    local gprPath=$1
    echo "[$(get_datetime)] [$gprPath] Start cleaning" | tee -a "$globalLogFilePath"
    # Remove ASIS AST
    rm -f *.ali *.adt
    echo "[$(get_datetime)] [$gprPath] End cleaning" | tee -a "$globalLogFilePath"
}

`;
}

function generateProjectsArray(projects: extendedGPRProject[], command: string[]): string {
    let projectsArray = "projects=(\n";
    for (const project of projects) {
        const finalCommand = command
        .map(item => item.includes("%PRJ%") ?
            item.replace("%PRJ%", "$PROJECT_ROOT/" + project.gprPath) : item)
        .map(item => item.includes("%UNITS%") ?
            item.replace("%UNITS%", "$PROJECT_ROOT/" + project.gprPath.replace(".gpr", ".units")) : item)
        .map(item => item.includes("%PRJ_NAME%") ?
        item.replace("%PRJ_NAME%", basename(project.gprPath).replace(".gpr", "")) : item)
        .join(" ");
        projectsArray += `    "${project.crateName}|${project.alireTomlPath}|${project.gprPath}|${finalCommand}"\n`;
    }
    projectsArray += ")\n";
    return projectsArray;
}

function generateMainLogic(globalLogFilePath: string, projects: string): string {
    return `# Loop through arguments and handle options
while [[ "$#" -gt 0 ]]; do
    case $1 in
        --xpNum) xpNum="$2"; shift 2 ;;
        -j) max_procs="$2"; shift 2 ;;
        --rule) ruleFile="$2"; shift 2 ;;
        -s|--suffix) logSuffix="$2"; shift 2 ;;
        -h|--help) show_help; exit 0 ;;
        *) echo "Unknown option: $1"; show_help; exit 1 ;;
    esac
done

${projects}
# Prepare global variables
globalLogFilePath="${globalLogFilePath}"

# Clear the global log file
echo "" > "$globalLogFilePath"

# Get total number of projects
total_projects=\${#projects[@]}

# Process projects sequentially
for i in "\${!projects[@]}"; do
    project_number=$((i+1))
    process_project "\${projects[$i]}" "$project_number" "$total_projects"
done

echo "All projects processed."
`
}
