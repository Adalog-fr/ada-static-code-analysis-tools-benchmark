import { basename, join } from "jsr:@std/path@^0.225.1";
import { Command } from "https://deno.land/x/cmd@v1.2.0/mod.ts";
import { filterCompleteCrates, createBlock } from "../utils.ts";
import { extendedGPRProject, UnifiedCrateData } from "../types.ts";
import { PROJECT_ROOT } from "../../config.ts";

export function initializeModule(program: Command, settings: {
    commandName: string,
    description: string,
    command: string[],
    ruleFile: string,
}): void {
    program
        .command(settings.commandName)
        .description(
            settings.description
        )
        .action(() => {
            const crates: UnifiedCrateData = JSON.parse(Deno.readTextFileSync(join(PROJECT_ROOT, "cratesDB.json")));
            const projects : extendedGPRProject[] = filterCompleteCrates(crates.crates);

            const commandName = basename(settings.command[0]);

            let resultFile = generateScriptHeader(commandName, settings.ruleFile);
            resultFile += generateHelperFunctions(commandName);
            resultFile += generateMainLogic(commandName, generateProjectsArray(projects, settings.command));

            Deno.writeTextFileSync(join(PROJECT_ROOT, `${commandName}_benchmark.sh`), resultFile);
        });
}

function generateScriptHeader(commandName: string, ruleFile: string): string {
    return `#!/bin/bash

${createBlock("WARNING: DO NOT EDIT THIS FILE MANUALY\n" +
"This file is generated with: cogralys-bench-util bench-" + commandName)}

# Initialize variables
xpNum=0
# Default number of maximum processes
max_procs=0
# Root of the benchmark project
PROJECT_ROOT=$PWD
# Path to the rule file
ruleFile="${ruleFile}"
# Suffix of log file
logSuffix=""
# Extra arguments
extraArgs=""
`;
}

function generateHelperFunctions(commandName: string): string {
    return `
# Function to handle signal (CTRL+C, CTRL+\\)
function signalHandler()
{
  echo "Signal recieved, safely end the script"
  exit 1
}

# Function to get current date and time
get_datetime() {
    date "+%Y-%m-%d %H:%M:%S"
}

# Function to display help information
function show_help() {
    echo "Usage: $0 [--xpNum <number>] [-j <max_procs>] [-h|--help]"
    echo "  --xpNum <number>                   Set the experience number."
    echo "  -j <max_procs>                     Set the maximum number of processes."
    echo "  --rule <path>                      Set the path to the rule file."
    echo "  -s, --suffix <string>              Suffix used on the name of logs files."
    echo "  --extra-args <args>                Additional arguments to pass to the command."
    echo "  -r, --resume <step:projectStep>    Resume from a specific step and project step (e.g., 3:2)."
    echo "  -h, --help                         Show help information."
}

# Save the current state of the script. Useful to resume the script later.
save_checkpoint() {
  echo "$current_step:$current_project_step" > "$checkpoint_file"
}

# Load the script to the latest state (if exists)
load_checkpoint() {
  if [ -f "$checkpoint_file" ]; then
      IFS=':' read -r current_step current_project_step < "$checkpoint_file"
  else
      current_step=1
      current_project_step=1
  fi
}

# Function to process a single project
process_project() {
    local project_info=$1
    local project_number=$2
    local total_projects=$3
    IFS='|' read -r crateName alireTomlPath gprPath command <<< "$project_info"

    local base_name=$(basename "$gprPath" .gpr)
    local log_prefix="${commandName}-$base_name-$xpNum-j$max_procs$logSuffix"

    echo "[$(get_datetime)] [$project_number/$total_projects] START" | tee -a "$globalLogFilePath"
    cd "$PROJECT_ROOT/$alireTomlPath"

    echo "[$(get_datetime)] [START] processing $crateName > $alireTomlPath > $gprPath" | tee -a "$globalLogFilePath"

    # Clear the log file only if not resuming
    if [ "$resume_requested" = false ]; then
        echo "" > "$log_prefix.log"
    else
        echo -e "\\n## RESUME ##\\n" >> "$log_prefix.log"
    fi

    # Set current_project_step to 1 if it's empty or not a number
    if ! [[ "$current_project_step" =~ ^[0-9]+$ ]] ; then
        current_project_step=1
        save_checkpoint
    fi

    if [ $current_project_step -eq 1 ]; then
        run_command "$gprPath" "$log_prefix" "$command"
        current_project_step=2
        save_checkpoint
    fi
    if [ $current_project_step -eq 2 ]; then
        computeSize "$gprPath" "$log_prefix"
        current_project_step=3
        save_checkpoint
    fi
    if [ $current_project_step -eq 3 ]; then
        clean "$alireTomlPath"
        current_project_step=1
        save_checkpoint
    fi

    echo "[$(get_datetime)] [END] processing $crateName > $alireTomlPath > $gprPath" | tee -a "$globalLogFilePath"
    echo "[$(get_datetime)] [$project_number/$total_projects] END" | tee -a "$globalLogFilePath"
}

run_command() {
    local gprPath=$1
    local log_prefix=$2
    local command="$3"

    echo "[$(get_datetime)] [$gprPath] Start xp" | tee -a "$globalLogFilePath"
    /usr/bin/time -v -o "$log_prefix.time" alr exec -- $command 2>&1 | tee -a "$log_prefix.log" "$globalLogFilePath" > /dev/null
    jc --time -p -r < "$log_prefix.time" > "$log_prefix.time.json"
    echo "[$(get_datetime)] [$gprPath] End xp" | tee -a "$globalLogFilePath"
}

computeSize() {
    local gprPath=$1
    local log_prefix=$2
    echo "[$(get_datetime)] [$gprPath] Start computing ADT size" | tee -a "$globalLogFilePath"
    total_size=$(du -ch *.adt 2>/dev/null | tail -n 1 | cut -f 1)
    echo "{ \\"size\\": \\"$total_size\\" }" > "$log_prefix.size-adt.json"
    echo "[$(get_datetime)] [$gprPath] End computing ADT size" | tee -a "$globalLogFilePath"
}

clean() {
    local alireTomlPath=$1
    echo "[$(get_datetime)] [$alireTomlPath] Start cleaning" | tee -a "$globalLogFilePath"
    # Remove ASIS AST
    rm -f *.ali *.adt
    echo "[$(get_datetime)] [$alireTomlPath] End cleaning" | tee -a "$globalLogFilePath"
}

`;
}

function generateProjectsArray(projects: extendedGPRProject[], command: string[]): string {
    let projectsArray = "projects=(\n";
    for (const project of projects) {
        const finalCommand = command
        .map(item => item.includes("%PRJ%") ?
            item.replace("%PRJ%", "$PROJECT_ROOT/" + project.gprPath) : item)
        .map(item => item.includes("%UNITS%") ?
            item.replace("%UNITS%", "$PROJECT_ROOT/" + project.gprPath.replace(".gpr", ".units")) : item)
        .map(item => item.includes("%UNITS_BY_FILENAME%") ?
            item.replace("%UNITS_BY_FILENAME%", "$PROJECT_ROOT/" + project.gprPath.replace(".gpr", ".units_by_filename")) : item)
        .map(item => item.includes("%UNITS_BY_PATH%") ?
            item.replace("%UNITS_BY_PATH%", "$PROJECT_ROOT/" + project.gprPath.replace(".gpr", ".units_by_path")) : item)
        .map(item => item.includes("%PRJ_NAME%") ?
        item.replace("%PRJ_NAME%", basename(project.gprPath).replace(".gpr", "")) : item)
        .map(item => item.includes("%EXTRA_ARGS%") ?
        item.replace("%EXTRA_ARGS%", "$extraArgs") : item)
        .join(" ");
        projectsArray += `    "${project.crateName}|${project.alireTomlPath}|${project.gprPath}|${finalCommand}"\n`;
    }
    projectsArray += ")\n";
    return projectsArray;
}

function generateMainLogic(commandName: string, projects: string): string {
    return `# Initialize resume variables
resume_requested=false
# Loop through arguments and handle options
while [[ "$#" -gt 0 ]]; do
    case $1 in
        --xpNum) xpNum="$2"; shift 2 ;;
        -j) max_procs="$2"; shift 2 ;;
        --rule) ruleFile="$2"; shift 2 ;;
        -s|--suffix) logSuffix="$2"; shift 2 ;;
        --extra-args) extraArgs="$2"; shift 2 ;;
        -h|--help) show_help; exit 0 ;;
        -r|--resume)
          IFS=':' read -r resume_step resume_iteration <<< "$2"
          current_step=$resume_step
          current_project_step=$resume_iteration
          resume_requested=true
          shift 2 ;;
        *) echo "Unknown option: $1"; show_help; exit 1 ;;
    esac
done

${projects}
# Prepare global variables
globalLogFilePath="$PROJECT_ROOT/${commandName}-all-$xpNum-j$max_procs$logSuffix.log"

# Get total number of projects
total_projects=\${#projects[@]}

checkpoint_file="$PROJECT_ROOT/benchmark-${commandName}-$xpNum-$max_procs$logSuffix.checkpoint"

# Load the current state if not set by resume option
if [ "$resume_requested" = false ] && [ -f "$checkpoint_file" ]; then
    load_checkpoint
    resume_requested=true
fi

# Clear the global log file only if not resuming
if [ "$resume_requested" = false ]; then
    echo "" > "$globalLogFilePath"
else
    echo -e "\\n## RESUME ##\\n" >> "$globalLogFilePath"
fi

current_step=$((current_step-1))

trap 'signalHandler' SIGINT
trap 'signalHandler' SIGQUIT

# Process projects sequentially
for i in "\${!projects[@]}"; do
    if [ $i -lt $current_step ]; then
        continue
    fi
    project_number=$((i+1))
    current_step=$project_number
    save_checkpoint
    process_project "\${projects[$i]}" "$project_number" "$total_projects"
done

echo "All projects ($total_projects) processed."
rm "$checkpoint_file"
`
}
