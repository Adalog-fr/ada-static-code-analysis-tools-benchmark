<template>
  <div class="page">
    <header class="header">
      <div>
        <h1>Ada Static Analysis – Quick Charts</h1>
        <p class="subtitle">
          Load a benchmark result JSON file to quickly inspect performance charts.
        </p>
      </div>
      <label class="file-input">
        <span>Select a JSON file…</span>
        <input type="file" accept="application/json" @change="onFileChange" />
      </label>
    </header>

    <main class="main" v-if="error || !rawData">
      <p v-if="!rawData">No file loaded yet.</p>
      <p v-if="error" class="error">{{ error }}</p>
      <p class="hint">
        Tip: you can directly use the <code>results/result.json</code> file generated by the benchmark.
      </p>
    </main>

    <main v-else class="main">
      <section class="controls">
        <div class="control-group">
          <label>Scope</label>
          <select v-model="scope">
            <option value="global">Global</option>
            <option value="rule" :disabled="!ruleNames.length">By rule</option>
          </select>
        </div>

        <div class="control-group" v-if="scope === 'rule'">
          <label>Rule</label>
          <select v-model="selectedRule">
            <option disabled value="">-- select a rule --</option>
            <option v-for="rule in ruleNames" :key="rule" :value="rule">
              {{ rule }}
            </option>
          </select>
        </div>

        <div class="control-group">
          <label>Category (project size)</label>
          <select v-model="category">
            <option value="all">All</option>
            <option value="small">Small</option>
            <option value="medium">Medium</option>
            <option value="large">Large</option>
          </select>
        </div>

        <div class="control-group">
          <label>Metric</label>
          <select v-model="plotType">
            <option value="analysis_time">Analysis time</option>
            <option value="overhead">Overhead (parsing + populating)</option>
            <option value="total">Total execution time</option>
          </select>
        </div>

        <p class="info" v-if="activeLabel">
          {{ activeLabel }} – axes are logarithmic.
        </p>
      </section>

      <section class="chart-section">
        <canvas ref="canvasRef"></canvas>
        <p v-if="noData" class="hint">No valid points for this combination (metric, category, rule).</p>
      </section>
    </main>
  </div>
</template>

<script setup>
import { computed, onBeforeUnmount, onMounted, ref, watch } from 'vue'
import Chart from 'chart.js/auto'

const rawData = ref(null)
const error = ref('')

const scope = ref('global')
const selectedRule = ref('')
const category = ref('all')
const plotType = ref('analysis_time')

const canvasRef = ref(null)
let chartInstance = null

const toolMapping = {
  adactl: 'AdaControl',
  cogralys: 'Cogralys',
  gnatcheck_1cores: 'GNATcheck (1 core)',
  gnatcheck_32cores: 'GNATcheck (32 cores)'
}

const toolColors = ['#a855f7', '#22c55e', '#ef4444', '#3b82f6']
const toolPointStyles = ['circle', 'rectRot', 'cross', 'crossRot']

const ruleNames = computed(() => {
  if (!rawData.value || !rawData.value.rules) return []
  return Object.keys(rawData.value.rules).sort()
})

const activeLabel = computed(() => {
  const metricLabel =
    plotType.value === 'analysis_time'
      ? 'Analysis time (seconds)'
      : plotType.value === 'overhead'
      ? 'Overhead parsing + populating (seconds)'
      : 'Total execution time (seconds)'

  const scopeLabel = scope.value === 'global' ? 'Global' : `Rule "${selectedRule.value || '?'}"`

  return `${scopeLabel} – ${metricLabel}`
})

const noData = ref(false)

function onFileChange(event) {
  const file = event.target.files?.[0]
  if (!file) return

  error.value = ''

  const reader = new FileReader()
  reader.onload = () => {
    try {
      const json = JSON.parse(reader.result)
      rawData.value = json

      if (!json.global || !json.global.all || !Array.isArray(json.global.all.projects)) {
        throw new Error('JSON does not match the expected format (missing global/all/projects).')
      }

      if (!ruleNames.value.includes(selectedRule.value)) {
        selectedRule.value = ''
      }
    } catch (e) {
      console.error(e)
      error.value = 'JSON parsing error: ' + e.message
      rawData.value = null
    }
  }
  reader.onerror = () => {
    error.value = 'Unable to read the selected file.'
  }
  reader.readAsText(file)
}

function getValueForProject(project, toolKey) {
  if (!project.results || !project.results[toolKey]) return null
  const r = project.results[toolKey]

  if (plotType.value === 'analysis_time') {
    return r.analysisTime ?? null
  }

  if (plotType.value === 'overhead') {
    const p = r.overheadParsing ?? 0
    const pop = r.overheadPopulating ?? 0
    const sum = p + pop
    return sum > 0 ? sum : null
  }

  if (plotType.value === 'total') {
    return r.executionTime ?? null
  }

  return null
}

function buildDatasets() {
  if (!rawData.value) return []

  let dataCategory
  if (scope.value === 'global') {
    dataCategory = rawData.value.global?.[category.value]
  } else {
    if (!selectedRule.value) return []
    dataCategory = rawData.value.rules?.[selectedRule.value]?.[category.value]
  }

  if (!dataCategory || !Array.isArray(dataCategory.projects)) return []

  const projects = dataCategory.projects

  const datasets = []
  const toolKeys = Object.keys(toolMapping)

  toolKeys.forEach((toolKey, index) => {
    const label = toolMapping[toolKey]
    const color = toolColors[index % toolColors.length]
    const pointStyle = toolPointStyles[index % toolPointStyles.length]

    const points = []
    for (const project of projects) {
      const loc = project.scc?.nbLoC
      const y = getValueForProject(project, toolKey)
      if (!loc || !y || y <= 0) continue

      const result = project.results?.[toolKey] || {}
      const issuedMessages =
        result.issuedMessages && typeof result.issuedMessages.maxCount !== 'undefined'
          ? result.issuedMessages.maxCount
          : null

      points.push({
        x: loc,
        y,
        loc,
        projectName: project.crateName || project.gprPath || 'Unknown project',
        nbFiles: project.scc?.nbFiles ?? null,
        complexity: project.scc?.complexity ?? null,
        overheadParsing: result.overheadParsing ?? null,
        overheadPopulating: result.overheadPopulating ?? null,
        issuedMessages,
      })
    }

    if (points.length) {
      datasets.push({
        label,
        data: points,
        borderWidth: 0,
        pointBackgroundColor: color,
        pointBorderColor: color,
        pointRadius: 4,
        pointHoverRadius: 6,
        pointStyle,
      })
    }
  })

  return datasets
}

function rebuildChart() {
  if (!canvasRef.value || !rawData.value) return

  const datasets = buildDatasets()
  noData.value = !datasets.length

  if (chartInstance) {
    chartInstance.destroy()
    chartInstance = null
  }

  if (!datasets.length) return

  const ctx = canvasRef.value.getContext('2d')

  const yLabel =
    plotType.value === 'analysis_time'
      ? 'Analysis Time (s)'
      : plotType.value === 'overhead'
      ? 'Overhead (s)'
      : 'Execution Time (s)'

  chartInstance = new Chart(ctx, {
    type: 'scatter',
    data: { datasets },
    options: {
      animation: false,
      plugins: {
        legend: {
          position: 'bottom',
        },
        tooltip: {
          callbacks: {
            label(context) {
              const point = context.raw || {}
              const value = point.y

              const lines = []

              lines.push(`Project: ${point.projectName || 'Unknown'}`)
              lines.push(`Tool: ${context.dataset.label}`)

              if (point.loc) {
                lines.push(`Lines of Code: ${point.loc.toLocaleString()}`)
              }

              if (typeof point.nbFiles === 'number') {
                lines.push(`Number of files: ${point.nbFiles.toLocaleString()}`)
              }

              if (typeof point.complexity === 'number') {
                lines.push(`Complexity: ${point.complexity.toLocaleString()}`)
              }

              if (typeof value === 'number') {
                const metricLabel =
                  plotType.value === 'analysis_time'
                    ? 'Time'
                    : plotType.value === 'overhead'
                    ? 'Overhead'
                    : 'Execution time'
                lines.push(`${metricLabel}: ${value.toFixed(3)}s`)
              }

              if (typeof point.overheadParsing === 'number') {
                lines.push(`Overhead Parsing: ${point.overheadParsing.toFixed(3)}s`)
              }

              if (typeof point.overheadPopulating === 'number') {
                lines.push(`Overhead Populating: ${point.overheadPopulating.toFixed(3)}s`)
              }

              if (typeof point.issuedMessages === 'number') {
                lines.push(`Issued Messages: ${point.issuedMessages.toLocaleString()}`)
              }

              return lines
            },
          },
        },
      },
      scales: {
        x: {
          type: 'logarithmic',
          title: { display: true, text: 'Lines of Code' },
        },
        y: {
          type: 'logarithmic',
          title: { display: true, text: yLabel },
        },
      },
    },
  })
}

onMounted(() => {
  rebuildChart()
})

onBeforeUnmount(() => {
  if (chartInstance) {
    chartInstance.destroy()
    chartInstance = null
  }
})

watch([rawData, scope, selectedRule, category, plotType], () => {
  rebuildChart()
})
</script>

